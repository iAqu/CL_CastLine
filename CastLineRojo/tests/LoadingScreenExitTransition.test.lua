local playerDataService = read("src/ServerScriptService/Services/PlayerDataService.lua")

assert(loadingScreen:find('Workspace:FindFirstChild("Areas")', 1, true))
assert(loadingScreen:find('areas:FindFirstChild("LoadingScreenCam")', 1, true))
assert(loadingScreen:find("camera.CFrame = cameraPart.CFrame", 1, true))
assert(loadingScreen:find("camera.CameraType = Enum.CameraType.Scriptable", 1, true))
assert(loadingScreen:find("camera.CameraType = Enum.CameraType.Custom", 1, true))
assert(loadingScreen:find('LoadingScreenMenu must contain LoadingGui.Frame.Frame', 1, true))
assert(loadingScreen:find("LoadingAttributes.PLAYER_DATA_LOADED", 1, true))
assert(loadingScreen:find("LoadingAttributes.CLIENT_CONTROLLERS_READY", 1, true))
assert(loadingScreen:find('return 1, "Loading player data...", false', 1, true))
assert(loadingScreen:find('return 1, "Loading controllers...", false', 1, true))
assert(loadingScreen:find('return 1, "Ready!", true', 1, true))
assert(loadingScreen:find("if ready then", 1, true))
assert(loadingScreen:find("local ENTRY_FADE_DURATION_SECONDS = 0.4", 1, true))
assert(loadingScreen:find("local ENTRY_CAMERA_DURATION_SECONDS = 1.25", 1, true))
