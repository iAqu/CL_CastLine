local fadeStart = assert(loadingScreen:find("local fadeTween = fadeLoadingPresentation()", 1, true))
local fadeCompleted = assert(loadingScreen:find("fadeTween.Completed:Wait()", fadeStart, true))
local disconnectAfterFade = assert(loadingScreen:find("disconnectConnections()", fadeCompleted, true))
local targetSample = assert(loadingScreen:find("sampleEntryCameraTarget(", disconnectAfterFade, true))
local entryAnimation = assert(loadingScreen:find("RunService:BindToRenderStep(ENTRY_CAMERA_BINDING_NAME", targetSample, true))

assert(fadeStart < fadeCompleted, "loading fade must complete before continuing")
assert(fadeCompleted < disconnectAfterFade, "loading camera must remain locked until the fade completes")
assert(disconnectAfterFade < targetSample, "camera target sampling must start after the fade")
assert(targetSample < entryAnimation, "entry camera animation must start after target sampling")
local handoff = assert(loadingScreen:find("handoffEntryCamera(camera, targetCFrame, targetFocus)", entryAnimation, true))
local zoomRestored = assert(loadingScreen:find("localPlayer.CameraMaxZoomDistance = originalMaxZoomDistance", handoff, true))
local settledFrame = assert(loadingScreen:find("RunService.RenderStepped:Wait()", zoomRestored, true))
local entryReturn = assert(loadingScreen:find("return true", zoomRestored, true))
assert(settledFrame < entryReturn, "Scene UI must wait through a frame with the default camera and restored zoom")
assert(loadingScreen:find("ENTRY_CAMERA_TARGET_SAMPLE_BINDING_NAME", 1, true))
assert(loadingScreen:find("ENTRY_CAMERA_TARGET_SAMPLE_FRAMES = 2", 1, true))
assert(not loadingScreen:find("PlotSlotId", 1, true))
assert(not loadingScreen:find("LOCAL_FARM_LOADED", 1, true))
