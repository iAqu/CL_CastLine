local new = require("./helpers/FishingHarness")

local success = new()
success.begin()
local selecting = success.presentation()
assert(selecting.phase == "Selecting" and selecting.rodId == "Rod_101" and selecting.plot == "Plot_1")
assert(selecting.token == nil and selecting.catchId == nil)
assert(success.client:SelectBait(success.player, success.token, "NONE").ok)
local preparing = success.presentation()
assert(preparing.phase == "Preparing" and preparing.id == selecting.id and preparing.baitId == "NONE")
success.cast()
local cast = success.presentation()
assert(cast.phase == "Cast" and cast.distance > 0 and cast.castRating and cast.startedAt < success.now)
assert(cast.catchId == nil and cast.weight == nil and cast.mutationId == nil and cast.seed == nil)
assert(not success.client:Hook(success.player, success.token, success.round.round, success.now - 10).ok)
assert(success.presentation() == cast)
success.onGrant = function()
	assert(success.presentation().catchId == nil)
end
local caught = success.hook()
assert(caught.ok and success.grants == 1)
assert(not success.client:Hook(success.player, success.token, success.round.round, success.now).ok)
success.advance(2)
assert(success.presentation() == cast, "fish must remain private during struggle")
success.advance(1.01)
local reveal = success.presentation()
assert(reveal.phase == "Catch" and reveal.id == cast.id and reveal.catchId == caught.catchId)
assert(reveal.weight == caught.weight and reveal.isNewDiscovery and reveal.startedAt <= success.now)
success.client:Cancel(success.player, success.token, true)
assert(success.presentation() == nil and #success.equippedCatches == 1)

local retry = new()
retry.begin("NONE")
retry.cast()
local retryCast = retry.presentation()
retry.now = retry.round.retryAt + 0.1
assert(retry.client:NextRound(retry.player, retry.token, retry.round.round).ok)
assert(retry.presentation() == retryCast, "normal bite retry must keep the line in the water")
retry.client:Cancel(retry.player, retry.token, false, retry.round.round)
assert(retry.presentation() == nil, "cancel with a stale round must not play an empty reel")

local reel = new()
reel.begin("NONE")
reel.cast()
reel.client:Cancel(reel.player, reel.token, false, reel.round.round)
local empty = reel.presentation()
assert(empty.phase == "EmptyReel" and empty.catchId == nil and empty.expiresAt > reel.now)
assert(not reel.service:IsActive(reel.player))
reel.advance(0.4)
assert(reel.presentation() == empty)
reel.begin()
local replacement = reel.presentation()
reel.advance(1)
assert(reel.presentation() == replacement and replacement.id ~= empty.id)
reel.cancel()
assert(reel.presentation() == nil)

local canceledCatch = new()
canceledCatch.begin("NONE")
canceledCatch.cast()
assert(canceledCatch.hook().ok)
canceledCatch.cancel()
canceledCatch.begin()
local current = canceledCatch.presentation()
canceledCatch.advance(61)
assert(canceledCatch.presentation() == current, "a stale catch or timeout must not overwrite a newer presentation")

local failedGrant = new()
failedGrant.begin("NONE")
failedGrant.cast()
failedGrant.failGrant = true
assert(not failedGrant.hook().ok)
failedGrant.advance(4)
assert(failedGrant.presentation().phase == "Cast" and failedGrant.presentation().catchId == nil)

local lifecycle = new()
lifecycle.service:KnitStart()
lifecycle.begin("NONE")
lifecycle.cast()
lifecycle.client:Cancel(lifecycle.player, lifecycle.token, false, lifecycle.round.round)
lifecycle.humanoid.Died:Fire()
assert(lifecycle.presentation() == nil)
lifecycle.begin()
lifecycle.plot.OwnerUserId = 0
lifecycle.slotReleased:Fire(lifecycle.plot)
assert(lifecycle.presentation() == nil)
lifecycle.plot.OwnerUserId = lifecycle.player.UserId
lifecycle.begin()
lifecycle.player.CharacterRemoving:Fire(lifecycle.player.Character)
assert(lifecycle.presentation() == nil)
lifecycle.begin()
lifecycle.playerRemoving:Fire(lifecycle.player)
assert(lifecycle.presentation() == nil)
