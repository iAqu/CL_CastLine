local function read(path)
	local file = assert(io.open(path, "r"))
	local source = file:read("*a")
	file:close()
	return source
end

local constants = read("src/ReplicatedStorage/Modules/Constants.lua")
local helper = read("src/ReplicatedStorage/Modules/PotionFeatureHelper.lua")
local potionService = read("src/ServerScriptService/Services/PotionService.lua")
local purchaseService = read("src/ServerScriptService/Services/PurchaseService.lua")
local randomPotion = read("src/ServerScriptService/Services/RandomPotionService.lua")
local givePotion = read("src/ServerScriptService/Cmdr/Commands/GivePotionServer.lua")
local storeGui = read("src/StarterPlayer/StarterPlayerScripts/Controllers/GUI/StoreGuiController.lua")

assert(constants:find("Constants.POTION_ACQUISITION_ENABLED = false", 1, true), "Potion acquisition must default to disabled")
assert(helper:find("function PotionFeatureHelper.IsAcquisitionEnabled", 1, true), "Potion feature gate must have a public predicate")
assert(helper:find("function PotionFeatureHelper.IsPotionReward", 1, true), "Potion feature gate must identify Potion rewards")
assert(potionService:find("not allowDisabledPotionGrant and not PotionFeatureHelper.IsAcquisitionEnabled()", 1, true), "PotionService must reject normal grants while disabled")
assert(purchaseService:find("ProductPurchases.Process(receiptInfo)", 1, true), "Existing developer product receipts must enter the durable receipt handler")
assert(purchaseService:find("PotionFeatureHelper.IsPotionRelatedPurchaseId(purchaseId)", 1, true), "Potion purchase prompts must be blocked")
assert(randomPotion:find("PotionFeatureHelper.ACQUISITION_DISABLED_MESSAGE", 1, true), "Random Potion must reject before charging")
assert(givePotion:find("PotionFeatureHelper.ACQUISITION_DISABLED_MESSAGE", 1, true), "givePotion must be disabled")
assert(not storeGui:find("InitPotionsData", 1, true), "Store must not initialize Potion products")
assert(not storeGui:find("PromptPurchase:Fire(\"PotionBundle\")", 1, true), "Store must not prompt PotionBundle purchases")
local hiddenStoreFrames = assert(storeGui:match('for _, frameName in ipairs%((.-)%) do'))
assert(hiddenStoreFrames:find('"PotionFrame"', 1, true), "Store must include the Potion section among the hidden frames")
assert(storeGui:find("frame.Visible = false", 1, true), "Store must hide the retired frames")

print("PotionFeatureDisable.test.lua passed")
