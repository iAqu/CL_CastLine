local function read(path)
	local file = assert(io.open(path, "r"))
	local source = file:read("*a")
	file:close()
	return source
end

local data = read("src/ReplicatedFirst/Data/ShovelsData.lua")
local template = read("src/ReplicatedStorage/PlayerData/Template.lua")
local playerDataService = read("src/ServerScriptService/Services/PlayerDataService.lua")
local shovelService = read("src/ServerScriptService/Services/ShovelService.lua")
local shovelToolUtil = read("src/ReplicatedStorage/Modules/ShovelToolUtil.lua")
local controller = read("src/StarterPlayer/StarterPlayerScripts/Controllers/GUI/ShovelShopGuiController.lua")
local guiAnimation = read("src/ReplicatedStorage/Modules/GuiAnimation.lua")

local function formatLuck(luck)
	local percent = math.floor(luck * 100 + 0.5)
	return (percent >= 0 and "+" or "") .. percent .. "%"
end

assert(formatLuck(0.05) == "+5%", "Decimal Luck must display as a signed percentage")
assert(data:find("Luck: number", 1, true), "Shovel configs must expose numeric Luck")
assert(data:find("Icon: string", 1, true), "Shovel configs must expose image icons")
assert(template:find("OwnedShovelIds = {", 1, true), "New profiles need persistent shovel ownership")
assert(template:find("Shovel_101 = true", 1, true), "The default shovel must start owned")
assert(playerDataService:find("ownedShovelIds[DEFAULT_SHOVEL_ID] = true", 1, true), "Profile migration must retain the default shovel")
assert(playerDataService:find("ownedShovelIds[equippedShovelId] = true", 1, true), "Profile migration must retain a valid equipped shovel")
assert(playerDataService:find("ShovelsData[equippedShovelId]", 1, true), "Invalid equipped shovel ids must be rejected")

assert(shovelService:find("function ShovelService:PurchaseAndEquipShovel", 1, true), "The server must own purchases")
assert(shovelService:find("function ShovelService:EquipShovel", 1, true), "The server must own equip changes")
assert(shovelService:find("if ownedShovelIds[shovelId] then", 1, true), "Repeat purchases must be rejected")
assert(shovelService:find("if not ownedShovelIds[shovelId] then", 1, true), "Unowned shovels must not be equipable")
assert(shovelService:find("self._Requests[player]", 1, true), "Purchase and equip requests must be serialized")
assert(shovelService:find("PlayerDataService:AdjustWins(player, -shovel.Price, false)", 1, true), "Purchases must debit authoritative cash")
assert(shovelService:find("PlayerDataService:AdjustWins(player, shovel.Price, false)", 1, true), "Failed tool creation must refund cash")
assert(shovelService:find("ownedShovelIds[shovelId] = nil", 1, true), "Failed purchases must roll back ownership")
assert(shovelService:find("profile.Data.EquippedShovelId = previousShovelId", 1, true), "Failed equips must restore the prior shovel")
assert(shovelService:find("ShovelStateChanged:Fire", 1, true), "Successful changes must synchronize client state")
assert(shovelToolUtil:find("tool.TextureId = config.Icon", 1, true), "Shovel tools must use their configured icon")

assert(controller:find('WaitForChild("ShovelShop")', 1, true), "The controller must bind the authored ShovelShop GUI")
assert(controller:find("SHOVEL_TEMPLATE.Visible = false", 1, true), "The source template must stay hidden")
assert(controller:find("table.sort(configs", 1, true), "Shovels must be sorted from their data table")
assert(controller:find("a.config.LayoutOrder < b.config.LayoutOrder", 1, true), "LayoutOrder must determine list order")
assert(controller:find('priceLabel.Text = "$" .. tostring(config.Price)', 1, true), "Prices must use the requested dollar format")
assert(controller:find("formatLuck(config.Luck)", 1, true), "Luck must come from ShovelsData")
