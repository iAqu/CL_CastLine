assert(controller:find("ShopHighlightUtil.Apply(highlight, highlightTarget)", 1, true), "The shop must use the shared highlight style")
assert(controller:find("GuiAnimation.OpenGui(SHOVEL_GUI)", 1, true), "The shop must use the shared open animation")
assert(controller:find("GuiAnimation.CloseGui(SHOVEL_GUI)", 1, true), "The shop must use the shared close animation")
