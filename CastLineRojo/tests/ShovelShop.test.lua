assert(controller:find('FindFirstChild("ShovelImage")', 1, true), "Shop entries must bind their authored shovel image")
assert(controller:find("shovelImage.Image = config.Icon", 1, true), "Shop entries must use configured shovel icons")
assert(controller:find("buyButton.Visible = not isOwned", 1, true), "Only unowned shovels may show Buy")
