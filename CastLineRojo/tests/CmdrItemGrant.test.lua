local function read(path)
	local file = assert(io.open(path, "r"))
	local source = file:read("*a")
	file:close()
	return source
end

local itemType = read("src/ServerScriptService/Cmdr/Types/item.lua")
local grantUtil = read("src/ServerScriptService/Services/ItemGrantUtil.lua")
local giveItem = read("src/ServerScriptService/Cmdr/Commands/GiveItem.lua")
local giveItemServer = read("src/ServerScriptService/Cmdr/Commands/GiveItemServer.lua")
local giveRandomItem = read("src/ServerScriptService/Cmdr/Commands/GiveRandomItem.lua")
local giveRandomItemServer = read("src/ServerScriptService/Cmdr/Commands/GiveRandomItemServer.lua")
local permissions = read("src/ServerScriptService/Cmdr/Hooks/Permission.lua")

assert(itemType:find('RegisterType("item"', 1, true), "Cmdr must register an item type")
assert(itemType:find("ReplicatedStorage.Modules.FishInventoryData", 1, true), "Client Cmdr types must read replicated item data")
assert(not itemType:find("ServerScriptService", 1, true), "Client Cmdr types must not depend on server-only services")
assert(grantUtil:find("ItemStatUtil.RollWeight(item, random)", 1, true), "Granted items must roll weights")
assert(grantUtil:find("ItemToolUtil.Create", 1, true), "Granted items must create a Tool")
assert(grantUtil:find("profile.Data.Items[instanceId]", 1, true), "Granted items must persist before use")
assert(giveItem:find('Name = "giveItem"', 1, true), "giveItem command must exist")
assert(giveItem:find('Type = "item"', 1, true), "giveItem must accept configured item IDs")
assert(giveItemServer:find("ItemGrantUtil.Grant(player, itemId", 1, true), "giveItem must use shared grant logic")
assert(giveRandomItem:find('Name = "giveRandomItem"', 1, true), "giveRandomItem command must exist")
assert(giveRandomItemServer:find("random:NextInteger(1, #itemIds)", 1, true), "Random items must be uniformly selected")
assert(giveRandomItemServer:find("grantedCounts", 1, true), "Random command must report item distribution")
assert(permissions:find('"giveItem"', 1, true), "GM permission must include giveItem")
assert(permissions:find('"giveRandomItem"', 1, true), "GM permission must include giveRandomItem")
