"""Bake horizontal SwimLoop envelopes from the preserved meshes and animations.

Run with Blender's bundled Python (NumPy required). Includes neutral poses and
partial animation weights used by PlotFishController. No Studio assets change.
"""
import json
import math
from pathlib import Path
import sys

import numpy as np

PROJECT = Path(__file__).resolve().parents[1]
RIGS = PROJECT.parent / "assets/fish/Processed/RigV2"
sys.path.insert(0, str(RIGS))
from build import read  # noqa: E402
from measure import geometry  # noqa: E402


def envelope(rig, clip, version, bind_rotations, arrays=None):
    vertices, ids, weights, bones = arrays if arrays is not None else geometry(rig, version)
    bind = np.array([bone["position"] for bone in bones])
    offsets = vertices[:, None, :] - bind[ids]
    lower, upper = vertices.min(axis=0), vertices.max(axis=0)
    radius = float(np.linalg.norm(vertices[:, [0, 2]], axis=1).max())
    for frame in clip["frames"]:
        for influence in (.25, .5, .75, 1.):
            rotations, joints = [], []
            for index, bone in enumerate(bones):
                rotation = np.array(frame["rotationMatrices"].get(
                    bone["name"], [1, 0, 0, 0, 1, 0, 0, 0, 1]
                )).reshape(3, 3)
                angle = math.acos(float(np.clip((np.trace(rotation) - 1) / 2, -1, 1)))
                if influence < 1 and angle > 1e-7:
                    skew = (rotation - rotation.T) / (2 * math.sin(angle))
                    rotation = (np.eye(3) + math.sin(angle * influence) * skew
                                + (1 - math.cos(angle * influence)) * (skew @ skew))
                if bone["name"] in bind_rotations:
                    rest = np.array(bind_rotations[bone["name"]]).reshape(3, 3)
                    rotation = rest @ rotation @ rest.T
                parent = bone["parent"]
                joints.append(bind[index] if parent < 0 else
                              joints[parent] + rotations[parent] @ (bind[index] - bind[parent]))
                rotations.append(rotation if parent < 0 else rotations[parent] @ rotation)
            posed = ((np.einsum("nkij,nkj->nki", np.array(rotations)[ids], offsets)
                      + np.array(joints)[ids]) * weights[:, :, None]).sum(axis=1)
            lower = np.minimum(lower, posed.min(axis=0))
            upper = np.maximum(upper, posed.max(axis=0))
            radius = max(radius, float(np.linalg.norm(posed[:, [0, 2]], axis=1).max()))
    # Same 10% interpolation allowance as the existing PresentationRadius bake.
    return [float(lower[0]) * 1.1, float(upper[0]) * 1.1,
            float(lower[2]) * 1.1, float(upper[2]) * 1.1, radius * 1.1]


def axolotl():
    rig = read("AxolotlSwim/rig.json")
    vertices = geometry(rig, 2)[0]
    skin = read("AxolotlSwim/weights.json")
    arrays = (vertices, np.array(skin["indices"]).reshape(-1, 4),
              np.array(skin["weights"]).reshape(-1, 4), rig["bones"])
    bounds = envelope(rig, read("AxolotlSwim/motion.json")["clips"]["SwimLoop"], 2, {}, arrays)
    published = read("AxolotlSwim/published.json")
    return ("Axolotl", published["mesh"] + "/" + published["clips"]["SwimLoop"], bounds)


def emit(rows):
    output = ["-- Generated by tools/measure-fish-swim-bounds.py; template units before item scaling.",
              "-- Key: primary mesh ID / SwimLoop ID. Values: min X, max X, min Z, max Z, horizontal radius.",
              "-- Includes neutral/partial-weight poses and a 10% interpolation allowance.",
              "return {"]
    grouped = {}
    for name, animation, bounds in rows:
        if animation in grouped:
            names, previous = grouped[animation]
            bounds = [min(previous[0], bounds[0]), max(previous[1], bounds[1]),
                      min(previous[2], bounds[2]), max(previous[3], bounds[3]), max(previous[4], bounds[4])]
            name = names + ", " + name
        grouped[animation] = (name, bounds)
    for animation, (name, bounds) in sorted(grouped.items()):
        fields = ", ".join(f"{value:.6f}" for value in bounds)
        output.append(f"\t[{json.dumps(animation)}] = {{ {fields} }}, -- {name}")
    output.append("}")
    (PROJECT / "src/ReplicatedStorage/Modules/FishSwimBounds.lua").write_text("\n".join(output) + "\n")


def main():
    rows = []
    for entry in read("inventory.json")["rows"]:
        key = entry["key"]
        rig = read(f"payload/{key}/rig.json")
        old = read(f"old-motion/{key}.json")
        legacy = envelope(rig, old["clips"]["SwimLoop"], 1, old.get("bindRotations", {}))
        name = "".join(entry["name"].split())
        animation = read(f"source/{key}/rig.json")["animations"]["SwimLoop"]
        rows.append((name, entry["parts"][0]["mesh"] + "/" + animation, legacy))
        print(name, flush=True)
    rows.append(axolotl())
    emit(rows)


if __name__ == "__main__":
    main()
